import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const databaseDir = path.join(
  projectRoot,
  ".wrangler",
  "state",
  "v3",
  "d1",
  "miniflare-D1DatabaseObject",
);
const snapshotPath = path.join(projectRoot, "data", "local-database-snapshot.sql");
const tableOrder = [
  "workspaces",
  "rooms",
  "containers",
  "items",
  "activity_logs",
];

function findDatabase() {
  let files;
  try {
    files = readdirSync(databaseDir)
      .filter((name) => name.endsWith(".sqlite") && name !== "metadata.sqlite")
      .map((name) => path.join(databaseDir, name))
      .sort((left, right) => statSync(right).mtimeMs - statSync(left).mtimeMs);
  } catch {
    throw new Error("No local database was found. Start LabSpace once, then try again.");
  }

  for (const file of files) {
    const database = new DatabaseSync(file, { readOnly: true });
    try {
      const names = new Set(
        database
          .prepare("SELECT name FROM sqlite_master WHERE type = 'table'")
          .all()
          .map((row) => row.name),
      );
      if (tableOrder.every((table) => names.has(table))) return { database, file };
    } catch {
      // Try the next SQLite file.
    }
    database.close();
  }

  throw new Error("The local database exists but does not contain the LabSpace tables.");
}

function quoteIdentifier(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function sqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot export non-finite number: ${value}`);
    return String(value);
  }
  if (typeof value === "bigint") return value.toString();
  if (value instanceof Uint8Array)
    return `X'${Buffer.from(value).toString("hex")}'`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

const { database, file } = findDatabase();
try {
  const rowsByTable = new Map();
  for (const table of tableOrder) {
    rowsByTable.set(
      table,
      database.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).all(),
    );
  }

  const statements = [
    "-- LabSpace portable local data snapshot.",
    "-- Generated by scripts/export-local-database.mjs.",
    "PRAGMA foreign_keys = OFF;",
    "BEGIN TRANSACTION;",
    'DELETE FROM "activity_logs";',
    'DELETE FROM "items";',
    'DELETE FROM "containers";',
    'DELETE FROM "rooms";',
    'DELETE FROM "workspaces";',
  ];

  for (const table of tableOrder) {
    for (const row of rowsByTable.get(table)) {
      const columns = Object.keys(row);
      statements.push(
        `INSERT INTO ${quoteIdentifier(table)} (${columns
          .map(quoteIdentifier)
          .join(", ")}) VALUES (${columns.map((column) => sqlValue(row[column])).join(", ")});`,
      );
    }
  }

  statements.push("COMMIT;", "PRAGMA foreign_keys = ON;");
  writeFileSync(snapshotPath, `${statements.join("\n")}\n`, "utf8");

  const counts = Object.fromEntries(
    tableOrder.map((table) => [table, rowsByTable.get(table).length]),
  );
  console.log(`Database: ${file}`);
  console.log(`Snapshot: ${snapshotPath}`);
  console.log(
    `Exported ${counts.rooms} rooms, ${counts.containers} containers, ${counts.items} items, and ${counts.activity_logs} activity logs.`,
  );
} finally {
  database.close();
}
